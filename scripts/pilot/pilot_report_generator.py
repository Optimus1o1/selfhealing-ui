"""
SelfHeal Pilot — Report Generator.
Moon Sanctum Labs -- Decode. Build. Evolve.

Reads pilot JSON results and YAML feedback to generate a markdown summary.

Usage:
    python scripts/pilot/pilot_report_generator.py --results-dir pilot_data/ --output pilot_summary.md

Read-only: does not modify any source files or databases.
"""

import argparse
import json
import sys
from pathlib import Path


def load_results(results_dir: Path) -> list[dict]:
    """Load all JSON result files from a directory."""
    results = []
    if not results_dir.exists():
        print(f"[REPORT] Results directory not found: {results_dir}")
        return results

    for json_file in sorted(results_dir.glob("*.json")):
        try:
            with open(json_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                data["_source_file"] = json_file.name
                results.append(data)
        except (json.JSONDecodeError, IOError) as e:
            print(f"[REPORT] Skipping {json_file.name}: {e}")

    print(f"[REPORT] Loaded {len(results)} result file(s)")
    return results


def compute_aggregate(results: list[dict]) -> dict:
    """Compute aggregate metrics from pilot results."""
    totals = {
        "participants": len(results),
        "total_scenarios": 0,
        "correct_healings": 0,
        "incorrect_healings": 0,
        "rejected_ambiguous": 0,
        "failed_to_heal": 0,
        "passed_without_healing": 0,
    }

    for result in results:
        if "scenarios" in result:
            for scenario in result["scenarios"]:
                totals["total_scenarios"] += 1
                outcome = scenario.get("actual_outcome", "")
                if outcome == "healed":
                    totals["correct_healings"] += 1
                elif outcome == "incorrect_healing":
                    totals["incorrect_healings"] += 1
                elif outcome == "rejected_ambiguous":
                    totals["rejected_ambiguous"] += 1
                elif outcome == "failed":
                    totals["failed_to_heal"] += 1
                elif outcome == "passed":
                    totals["passed_without_healing"] += 1

    healing_attempts = totals["correct_healings"] + totals["incorrect_healings"]
    eligible = totals["correct_healings"] + totals["failed_to_heal"] + totals["rejected_ambiguous"]

    totals["precision"] = (
        round(totals["correct_healings"] / healing_attempts * 100, 2) if healing_attempts > 0 else None
    )
    totals["recall"] = (
        round(totals["correct_healings"] / eligible * 100, 2) if eligible > 0 else None
    )
    totals["fpr"] = (
        round(totals["incorrect_healings"] / max(1, totals["total_scenarios"] - eligible) * 100, 2)
        if totals["incorrect_healings"] > 0
        else 0.0
    )

    return totals


def generate_markdown(results: list[dict], aggregates: dict) -> str:
    """Generate a markdown summary report."""
    lines = [
        "# SelfHeal Pilot — Aggregate Results Summary",
        "",
        "**Generated by:** `pilot_report_generator.py`  ",
        f"**Participants:** {aggregates['participants']}  ",
        f"**Total scenarios:** {aggregates['total_scenarios']}",
        "",
        "---",
        "",
        "## Aggregate Metrics",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Participants | {aggregates['participants']} |",
        f"| Total Scenarios | {aggregates['total_scenarios']} |",
        f"| Correct Healings | {aggregates['correct_healings']} |",
        f"| Incorrect Healings | {aggregates['incorrect_healings']} |",
        f"| Rejected (Ambiguous) | {aggregates['rejected_ambiguous']} |",
        f"| Failed to Heal | {aggregates['failed_to_heal']} |",
        f"| Passed Without Healing | {aggregates['passed_without_healing']} |",
        f"| **Precision** | **{aggregates['precision']}%** |" if aggregates["precision"] is not None else "| Precision | N/A |",
        f"| **Recall** | **{aggregates['recall']}%** |" if aggregates["recall"] is not None else "| Recall | N/A |",
        f"| **FPR** | **{aggregates['fpr']}%** |",
        "",
        "---",
        "",
        "## Per-Participant Summary",
        "",
        "| Source File | Scenarios | Correct | Incorrect | Rejected |",
        "|---|---|---|---|---|",
    ]

    for result in results:
        source = result.get("_source_file", "unknown")
        scenarios = result.get("scenarios", [])
        correct = sum(1 for s in scenarios if s.get("actual_outcome") == "healed")
        incorrect = sum(1 for s in scenarios if s.get("actual_outcome") == "incorrect_healing")
        rejected = sum(1 for s in scenarios if s.get("actual_outcome") == "rejected_ambiguous")
        lines.append(f"| {source} | {len(scenarios)} | {correct} | {incorrect} | {rejected} |")

    lines.extend([
        "",
        "---",
        "",
        "*Moon Sanctum Labs — Decode. Build. Evolve.*",
    ])

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="SelfHeal Pilot — Generate summary from pilot results"
    )
    parser.add_argument(
        "--results-dir",
        default="pilot_data",
        help="Directory containing pilot result JSON files",
    )
    parser.add_argument("--output", help="Output markdown file path")

    args = parser.parse_args()
    results_dir = Path(args.results_dir)
    results = load_results(results_dir)

    if not results:
        print("[REPORT] No results found. Nothing to generate.")
        sys.exit(0)

    aggregates = compute_aggregate(results)
    markdown = generate_markdown(results, aggregates)

    if args.output:
        output_path = Path(args.output)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(markdown)
        print(f"[REPORT] Summary saved to {output_path}")
    else:
        print(markdown)


if __name__ == "__main__":
    main()

